const defaultFacesFor = (target) => {
  if (aFaceEnergyOptions.includes(target)) {
    return [target, target, target, `${target}/${target}`, `${target}/${target}`, '悪']
  }
  return ['鋼', target, target, `${target}/${target}`, `${target}/${target}`, target]
}

const normalizeMoves = (character) => ({
  ...character,
  energyCoros: Array.from({ length: 3 }, () => defaultFacesFor(character.energyTarget)),
  moves: character.moves.map(([id, name, required, damage]) => ({
    id,
    name,
    required,
    damage,
  })),
})

